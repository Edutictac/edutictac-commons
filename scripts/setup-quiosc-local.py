#!/usr/bin/env python3
"""One administrative setup on the Epoptes server; no teacher/student setup.

--check inspects only. --deploy also recreates id-api/portal with current images.
--auto is used by the package and by edutictac-quiosc-prepare.service: it exits
quietly when there is no Epoptes server and rewrites nothing when already prepared.
Preparation never enables Quiosc; an administrator does that from the panel.
No passwords are requested, printed, copied or generated by this installer.
"""
import argparse
import importlib.util
import json
import os
import re
from pathlib import Path
import shutil
import socket
import stat
import struct
import subprocess
import tempfile


def read_env(path):
    values = {}
    for line in path.read_text().splitlines():
        if line and not line.lstrip().startswith('#') and '=' in line:
            key, value = line.split('=', 1)
            values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def atomic_write(path, text, mode, uid=0, gid=0):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix='.quiosc-', dir=path.parent)
    try:
        os.fchmod(descriptor, mode)
        os.fchown(descriptor, uid, gid)
        with os.fdopen(descriptor, 'w') as stream:
            stream.write(text)
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def inspect_server(project, socket_path, url=None):
    metadata = socket_path.lstat()
    if not stat.S_ISSOCK(metadata.st_mode) or metadata.st_uid != 0:
        raise ValueError('Cal el socket del servidor Epoptes, propietat de root')
    with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as probe:
        probe.settimeout(3)
        probe.connect(str(socket_path))
        _, uid, _ = struct.unpack('3i', probe.getsockopt(socket.SOL_SOCKET, socket.SO_PEERCRED, struct.calcsize('3i')))
        if uid != 0:
            raise ValueError('No es pot verificar el servidor Epoptes')
        peer_path = probe.getpeername()
    spec = importlib.util.spec_from_file_location('epoptes_transport', project / 'services/id-api/quiosc/epoptes.py')
    transport = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(transport)
    # Protocol check, without sending any execution commands to pupils.
    transport.Epoptes(str(socket_path), timeout=3).handles()
    env = read_env(project / '.env')
    if len(env.get('EDUTICTAC_ID_SECRET', '')) < 32:
        raise ValueError('Commons necessita una clau de firma de producció ja configurada')
    puid, pgid = int(env.get('PUID', '1000')), int(env.get('PGID', '1000'))
    if puid <= 0 or pgid < 0:
        raise ValueError('Commons ha d’executar-se amb un usuari no root')
    parent = socket_path.parent.stat()
    can_traverse = parent.st_mode & 0o001 or parent.st_gid == metadata.st_gid and parent.st_mode & 0o010 or parent.st_uid == puid and parent.st_mode & 0o100
    can_connect = metadata.st_mode & 0o002 or metadata.st_mode & 0o020 or metadata.st_uid == puid and metadata.st_mode & 0o200
    if not can_traverse or not can_connect:
        raise ValueError('La connexió Docker requerix revisar els permisos del servidor; no es canviaran els d’Epoptes')
    base_url = (url or 'http://127.0.0.1:' + env.get('PORTAL_PORT', '8082')).rstrip('/')
    # Reuse the launcher's strict URL validation, without opening a browser.
    spec = importlib.util.spec_from_file_location('quiosc_launcher', project / 'scripts/quiosc-local-launcher.py')
    launcher = importlib.util.module_from_spec(spec); spec.loader.exec_module(launcher)
    server, _ = launcher.handoff_server({'commons_url': base_url}, 'validation-only', uid=os.getuid())
    server.server_close()
    server_macs = sorted({p.read_text().strip().lower() for p in Path('/sys/class/net').glob('*/address')
                          if re.fullmatch(r'(?:[0-9a-fA-F]{2}:){5}[0-9a-fA-F]{2}', p.read_text().strip())
                          and p.read_text().strip() != '00:00:00:00:00:00'})
    return {
        'QUIOSC_SERVER_MACS': ','.join(server_macs),
        'QUIOSC_DISCOVERY': 'epoptes', 'QUIOSC_LOCAL_AUTH': '1',
        'QUIOSC_EPOPTES_DIR': str(socket_path.parent), 'QUIOSC_SOCKET_GID': str(metadata.st_gid),
        'QUIOSC_HOST_EPOPTES_SOCKET': peer_path, 'QUIOSC_BROKER_DIR': '/run/edutictac-quiosc',
        'QUIOSC_LOCAL_URL': base_url,
    }, puid, pgid


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--socket', type=Path, default=Path('/run/epoptes/epoptes.socket'))
    parser.add_argument('--url', help='Només administració; per defecte, el portal local existent')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--deploy', action='store_true')
    parser.add_argument('--auto', action='store_true', help='Preparació automàtica del paquet i de systemd')
    args = parser.parse_args()
    project = args.project.resolve()
    if args.auto and not args.socket.exists():
        print('Sense servidor Epoptes local; Quiosc no es prepara en este equip')
        return
    if not args.socket.exists():
        raise ValueError('No hi ha servidor Epoptes local. Executa esta preparació en l’ordinador de l’aula que té Epoptes')
    values, puid, pgid = inspect_server(project, args.socket, args.url)
    print('Servidor Epoptes i protocol verificats; detecció automàtica disponible')
    resolved = subprocess.run(['docker', 'compose', '--env-file', str(project / '.env'), '-f', str(project / 'compose.yml'),
                               'config', '--format', 'json'], capture_output=True, text=True, check=True)
    image = json.loads(resolved.stdout)['services']['id-api']['image']
    capability = subprocess.run(['docker', 'run', '--rm', '--pull=never', '--network', 'none', '--entrypoint', 'python', image,
                                 '-c', 'from quiosc.local_auth import LocalAuth; from quiosc.service import Quiosc; assert hasattr(Quiosc, "automatic_room")'],
                                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if capability.returncode:
        raise ValueError('Actualitza primer la imatge Commons ID API amb la integració local de Quiosc')
    if args.check:
        return
    if os.getuid() != 0:
        raise ValueError('Esta preparació única requerix administració del servidor; el professorat no ha de configurar res')
    if not shutil.which('systemd-tmpfiles'):
        raise ValueError('No es pot garantir el directori de connexió després de reiniciar')
    env_path = project / '.env'
    metadata = env_path.stat()
    lines, seen = [], set()
    for line in env_path.read_text().splitlines():
        key = line.split('=', 1)[0]
        if key in values:
            lines.append(key + '=' + values[key]); seen.add(key)
        else:
            lines.append(line)
    lines += [key + '=' + value for key, value in values.items() if key not in seen]
    env_changed = '\n'.join(lines) + '\n' != env_path.read_text()
    directory = Path(values['QUIOSC_BROKER_DIR'])
    if directory.exists():
        meta = directory.lstat()
        if not stat.S_ISDIR(meta.st_mode) or meta.st_uid != puid or meta.st_mode & 0o022:
            raise ValueError('Directori de connexió local no segur')
    else:
        directory.mkdir(mode=0o755); os.chown(directory, puid, pgid)
    launcher = project / 'scripts/quiosc-local-launcher.py'
    target = Path('/usr/local/lib/edutictac-quiosc/launcher.py')
    atomic_write(target, launcher.read_text(), 0o755)
    atomic_write('/etc/edutictac-quiosc.json', json.dumps({
        'epoptes_socket': str(args.socket), 'broker_socket': str(directory / 'local-auth.socket'),
        'commons_url': values['QUIOSC_LOCAL_URL'],
    }, indent=2) + '\n', 0o644)
    atomic_write('/etc/tmpfiles.d/edutictac-quiosc.conf',
                 'd /run/edutictac-quiosc 0755 %d %d -\n' % (puid, pgid), 0o644)
    atomic_write('/usr/share/applications/edutictac-quiosc.desktop', '''[Desktop Entry]
Type=Application
Name=EduTicTac Quiosc
Comment=Activitats supervisades amb els permisos de la sessió Epoptes
Exec=/usr/bin/python3 /usr/local/lib/edutictac-quiosc/launcher.py
Icon=applications-education
Terminal=false
Categories=Education;
''', 0o644)
    if env_changed:
        atomic_write(env_path, '\n'.join(lines) + '\n', metadata.st_mode & 0o777, metadata.st_uid, metadata.st_gid)
    print('Entrada del menú preparada. No s’han modificat clients, comptes ni permisos d’Epoptes')
    # Si Quiosc ja estava actiu i canvia la connexió, cal recrear els serveis que la usen.
    active = read_env(env_path).get('QUIOSC_MODE', 'disabled') != 'disabled'
    if args.deploy or args.auto and active and env_changed:
        subprocess.run(['docker', 'compose', '--env-file', str(env_path), '-f', str(project / 'compose.yml'),
                        'up', '-d', '--no-build', '--no-deps', '--wait', '--wait-timeout', '120', 'id-api', 'portal'],
                       cwd=project, check=True)
    elif not args.auto:
        print('Cal recrear id-api i portal amb les imatges actualitzades abans d’obrir Quiosc')
    print('Quiosc preparat. Activa’l des d’Administració, en Eines del centre')
    module_manager = project / 'scripts/manage-modules.py'
    if module_manager.is_file():
        subprocess.run([__import__('sys').executable, str(module_manager), 'status', '--write'],
                       cwd=project, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)


if __name__ == '__main__':
    try:
        main()
    except Exception as exc:
        # Known validation messages contain no credentials; never emit external
        # exceptions, request payloads, resolved Compose config or environment.
        if isinstance(exc, ValueError):
            print(str(exc), file=__import__('sys').stderr)
        else:
            print('No s’ha pogut preparar Quiosc. Revisa el servidor Epoptes i la instal·lació de Commons.', file=__import__('sys').stderr)
        raise SystemExit(1)
